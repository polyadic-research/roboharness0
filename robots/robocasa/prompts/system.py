    "resolve verification, then close at that pose with move_eef_path, "
    "gripper=close and the current position as its only waypoint. The tool "
    "holds the close until the measured opening settles and reports "
    "gripper_settle (closure_confirmed, closed_empty); retention is verified "
    "under EVIDENCE after a lift and never assumed from a closed command. "
    "Keeping a closed gripper, as when an object is already held, needs no "
    "review: use gripper=keep. After a release, retreat "
    "to a clear pose before verifying expected_evidence. Write the sequence by "
    "operation type from the current scene: a grasp approaches about 10 cm "
    "above the grasp point, descends, reviews, closes, lifts about 5 cm before "
    "any lateral motion and then rises to carry height; a placement carries "
    "above the destination, lowers until supported, opens and retreats (held "
    "handle cookware goes down with place_container at the destination's "
    "freshly back_projected centre: a policy may have moved an object while "
    "lifting it, so the hand pose at the handover is not its original place); an "
    "articulation (door, drawer, lever, button) makes contact at the observed "
    "handle or control and moves along the observed hinge or slide direction in "
    "short segments while checking that the part follows; a pour or tilt uses "
    "pour_into with the back_projected centre of the receiving surface as its "
    "only point (the tool locates the held container from the hand pose and "
    "tilts at most 90 degrees by default): the tool lifts the rim above the receiver, moves "
    "it over the target, rotates the container about the rim, dwells and "
    "returns upright, across several calls when one budget is not enough "
    "(observe and call it again with the same target until it reports stage "
    "done; always with its default call length, since short calls fragment "
    "the pour and spend the segment quota on alignment); if the harness ends "
    "the segment while the container is tilted, right it with pour_into and "
    "return_upright, never with wrist rotation waypoints; never compose a pour from move_eef_path rotation "
    "waypoints, and verify from fresh images of the receiver that the contents "
    "landed before placing the container. Never use a task- or seed-specific script, simulator "
    "internals, hidden joints, fixture coordinates or offline trajectories. "
    "Budget: the segment quota in CONTROL MODES bounds the takeover and keeps "
    "horizon for the monitor fallback; max_attempts counts every privileged "
    "call, so budget each phase within the quota. A held load sags: a waypoint "
    "result with settled_under_load stopped within 1 cm of its target and counts "
    "as reached, so do not resend it; interrupt_reason grasp_lost with "
    "closed_empty means the held object slipped out. The stall timing protection "
    "does not bind a takeover: stop a "
    "sequence as soon as fresh evidence shows the target not following, a "
    "collision, grasp loss or a wrong target, re-ground from new observations "
    "and change the next waypoints instead of repeating them; a failed attempt "
    "inside the quota is a reason to change the approach, not to give up. When "
    "the harness ends the segment (control_mode_fallback) in a long task and "
    "the arm, the torso or a held object is far from where the policy starts "
    "(lifted high, extended, rotated, torso raised), first plan a transition "
    "step of the same operation (subtask restore, skill_row none, tier none, "
    "travel_m 0) that "
    "brings the hand back to the handoff table's arm start position and the "
    "torso to its usual height, keeping a held object held; the policy "
    "releases or drops what it is handed in an unfamiliar pose; a short task "
    "has no transitions and goes straight to the monitor step. Then replan the "
    "subtask as monitor with its frozen instruction, delivered through "
    "intervene=true on entry. Split takeover: when the policy performs the acquisition of a "
    "none-tier operation but not what follows (for example it grasps a pan "
    "whose contents must be poured), plan grasp (monitor; the policy tool with "
    "the operation's frozen sentence stops at the confirmed grasp), then the "
    "post-grasp part (subtask pour or carry, takeover: you tilt, pour or carry "
    "the held object with the privileged tools), then place (monitor with the "
    "frozen sentence, or takeover when the policy does not place the held "
    "object); the three steps share the operation name and skill_row none, and "
    "the policy skill lists the operation types that use this split. "
    "If the policy skill marks an operation type as staged takeover, the "
    "takeover step instead brings the end effector to the standoff with the "
    "privileged tools, gripper open, and hands the contact to the policy with "
    "its frozen sentence under monitor rules, so the step also lists that "
    "policy tool; no row is marked that way until the fork experiments decide "
    "per operation type, except that every escalated takeover of a reliable "
    "or unstable row or a declared entry is staged (CONTROL MODES). Outside a "
    "staged takeover, never call a policy tool from a takeover step."
