def burner_control_available(task: str, *, policy_family: str) -> bool:
    """Mirror the toolkit gate: burner_control needs the KettleBoiling task id.

    The RoboCasa runtime sends language-conditioned policies the environment
    sentence and every other family its training task id; the toolkit offers
    ``burner_control`` only when that policy instruction is ``KettleBoiling``.
    """
    return task == _KETTLE_TASK and policy_family not in LANGUAGE_POLICY_FAMILIES


