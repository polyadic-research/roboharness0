    "command of the call) and the body with navigate_to and adjust_torso_to. "
    "Prefer one multi-waypoint call per phase (approach, engage, lift or push, "
    "transport, place or actuate, retreat) over many small calls; every call is "
    "a model request against the episode liveness budget. Observe after each "
    "call: target_reached describes the end effector only, so confirm from "
    "fresh images and measured gripper width whether the target moved, is held "
    "or changed state. A direct close must first pass review_grasp on a fresh "
    "wrist image, exactly as for policy grasps: approach with the gripper open, "
