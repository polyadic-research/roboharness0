    "in the planning request (control_subtasks, control_segments, "
    "control_mode_failures, control_mode_fallbacks, control_mode_escalations). "
    "Only a verified fail or retry of a call that executed actions is a "
    "failure: a validation or parameter error, a guard rejection such as a "
